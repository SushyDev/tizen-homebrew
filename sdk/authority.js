const CERTIFICATES = {
    author: AUTHOR,
    Public: PUBLIC,
    Partner: PARTNER
};

const LEVELS = ['Public', 'Partner'];

const refuse = (message) => Object.assign(new Error(message), { code: 'authorityUnknown', isFriendly: true });

const load = (which) => {
    const pem = CERTIFICATES[which];

    if (!pem) {
        throw refuse(`There is no bundled certificate authority for "${which}" — expected ${LEVELS.join(' or ')}.`);
    }

    return pem;
};

const authorCa = () => load('author');
const distributorCa = (level) => load(level);

module.exports = { authorCa, distributorCa, LEVELS, CERTIFICATES };
